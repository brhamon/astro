#!/usr/bin/env python3
"""Generate src/star_names.inc from the IAU Catalog of Star Names (IAU-CSN).

The IAU-CSN is maintained by the IAU Division C Working Group on Star Names
(WGSN) and released under Creative Commons Attribution; download it from
    https://www.pas.rochester.edu/~emamajek/WGSN/IAU-CSN.txt
(official landing page: https://www.iau.org/public/themes/naming_stars/).

Usage:
    tools/extract_star_names.py IAU-CSN.txt > src/star_names.inc

The output is a sorted table of (lowercased ASCII proper name -> HIP number) for
the entries that have a Hipparcos number, consumed by src/catalog.cpp. Committed
so the build needs no network; re-run when the WGSN publishes a new edition.
"""
import re
import sys

def main() -> int:
    if len(sys.argv) != 2:
        sys.stderr.write("usage: extract_star_names.py IAU-CSN.txt\n")
        return 2
    pairs = []
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            if line.startswith(("#", "$")) or not line.strip():
                continue
            name = line[0:17].strip()          # Name/ASCII (fixed-width col 1)
            hipf = line[89:96].strip()          # HIP (fixed-width col 11)
            if not name or not re.fullmatch(r"\d+", hipf):
                continue                        # no Hipparcos number -> skip
            pairs.append((name.lower(), name, int(hipf)))
    pairs.sort()

    out = sys.stdout
    out.write("// IAU proper star name -> Hipparcos (HIP) number.\n")
    out.write("//\n")
    out.write("// Generated by tools/extract_star_names.py from the IAU Catalog of Star\n")
    out.write("// Names (IAU-CSN), maintained by the IAU WGSN and released under Creative\n")
    out.write("// Commons Attribution: https://www.iau.org/public/themes/naming_stars/\n")
    out.write("// Do not edit by hand. Entries are {lowercased name (for lookup),\n")
    out.write("// canonical IAU name (for display), HIP}, sorted by the lowercased name.\n")
    out.write(f"// {len(pairs)} named stars with a Hipparcos number.\n")
    out.write("constexpr NamedStar kStarNames[] = {\n")
    for lower, disp, hip in pairs:
        out.write(f'    {{"{lower}", "{disp}", {hip}}},\n')
    out.write("};\n")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
